DO $$
DECLARE
AGE INT:=17;
BEGIN
IF AGE >= 18 THEN
RAISE NOTICE 'You are eligible to vote';
ELSE
RAISE NOTICE 'You are not eligible to vote';
END IF;
END;
$$

DO $$
DECLARE 
VAL INT:=17;
BEGIN
IF VAL>=1 AND VAL <=10 THEN
RAISE NOTICE 'RANGE IS  BETWEEN 1 TO 10';
ELSIF VAL>10 AND VAL<=20 THEN
RAISE NOTICE 'RANGE IS  BETWEEN 11 TO 20';
ELSIF VAL>20 AND VAL<=30 THEN
RAISE NOTICE 'RANGE IS  BETWEEN 21 TO 30';
ELSE
RAISE NOTICE 'VALUE IS GREATER THEN 30';
END IF;
END;
$$